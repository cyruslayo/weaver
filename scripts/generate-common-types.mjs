#!/usr/bin/env node

// Deterministic generator for the built-in A2UI v1.0 common types resource.
//
// Every v1.0 catalog may reference `common_types.json#/$defs/...`, so Core
// resolves that document itself instead of requiring each catalog to embed it.
// This generator reads the pinned upstream copy and emits a platform-neutral
// module consumed by packages/core/src/catalog/common-types.ts:
//
//   packages/core/src/protocol/a2ui/v1_0/inbound/fixtures/common_types.json
//        -> this generator
//        -> packages/core/src/catalog/generated-common-types.ts
//
// The only normalization is the document identity: `$id` becomes the relative
// resource name `common_types.json`, which is how catalogs reference it. The
// `catalog.json#/$defs/anyFunction` reference in FunctionCall is kept verbatim;
// the registry rewrites it per catalog to that catalog's own function union.
// Any other external reference is a hard error.
//
// Run with --check to fail when the committed output is stale.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fixtures = path.join(root, "packages", "core", "src", "protocol", "a2ui", "v1_0", "inbound", "fixtures");
const output = path.join(root, "packages", "core", "src", "catalog", "generated-common-types.ts");

const UPSTREAM_ID = "https://a2ui.org/specification/v1_0/common_types.json";
const RESOURCE_ID = "common_types.json";
const UPSTREAM_COMMIT = "5ff1b05f02d39f969b52a942e78e864ef3ac01fa";
const ALLOWED_EXTERNAL_REFS = new Set(["catalog.json#/$defs/anyFunction"]);

function assertSupportedRefs(value) {
  if (Array.isArray(value)) return value.forEach(assertSupportedRefs);
  if (value === null || typeof value !== "object") return;
  for (const [key, entry] of Object.entries(value)) {
    if (key === "$ref") {
      if (typeof entry !== "string") throw new Error(`Unexpected $ref value: ${JSON.stringify(entry)}`);
      const local = entry.startsWith("#/$defs/");
      if (!local && !ALLOWED_EXTERNAL_REFS.has(entry)) throw new Error(`Unsupported $ref in common types: ${entry}`);
    } else {
      assertSupportedRefs(entry);
    }
  }
}

function generate() {
  let common;
  try {
    common = JSON.parse(readFileSync(path.join(fixtures, "common_types.json"), "utf8"));
  } catch (error) {
    throw new Error(`Could not read common types fixture: ${error instanceof Error ? error.message : String(error)}`);
  }
  if (common.$id !== UPSTREAM_ID) throw new Error(`Unexpected common types $id: ${common.$id}`);
  assertSupportedRefs(common.$defs);

  const resource = { $schema: common.$schema, $id: RESOURCE_ID, $defs: common.$defs };
  const json = JSON.stringify(resource, null, 2);
  return [
    "// @generated by scripts/generate-common-types.mjs. Do not edit this file directly;",
    "// edit scripts/generate-common-types.mjs and regenerate.",
    "//",
    "// Portions are derived from the A2UI v1.0 schema:",
    "//   a2ui-project/a2ui",
    `//   commit ${UPSTREAM_COMMIT}`,
    "//   specification/v1_0/json/common_types.json",
    "//",
    "// This representation has been normalized/modified for Weaver and is not an",
    "// exact copy: the document identity is the relative resource name. Redistribution",
    "// terms for the upstream material are in packages/core/THIRD_PARTY_LICENSES.txt.",
    "",
    'import type { JsonObject } from "../protocol/index.js";',
    "",
    `export const A2UI_V10_COMMON_TYPES_ID = ${JSON.stringify(RESOURCE_ID)};`,
    "",
    "export const A2UI_V10_COMMON_TYPES: JsonObject =",
    json,
    ";",
    "",
  ].join("\n");
}

const header = generate();
if (process.argv.includes("--check")) {
  const current = readFileSync(output, "utf8");
  if (current.replace(/\r\n/g, "\n") !== header) {
    process.stderr.write("Common types generated output is stale; run scripts/generate-common-types.mjs\n");
    process.exit(1);
  }
  process.stdout.write("Common types generated output is up to date.\n");
} else {
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, header);
  process.stdout.write(`Wrote ${path.relative(root, output)}\n`);
}
